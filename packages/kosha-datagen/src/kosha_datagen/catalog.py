@dataclass(frozen=True, slots=True)
class City:
    name: str
    district: str
    state: S
    pincodes: tuple[int, int]
    lat: Decimal
    lng: Decimal
    weight: int
    region: str
    localities: tuple[str, ...]


def _city(  # noqa: PLR0917 — one positional argument per column of a table row
    name: str,
    district: str,
    state: S,
    pincodes: tuple[int, int],
    lat: str,
    lng: str,
    weight: int,
    region: str,
    localities: str,
) -> City:
    return City(
        name,
        district,
        state,
        pincodes,
        Decimal(lat),
        Decimal(lng),
        weight,
        region,
        tuple(localities.split(", ")),
    )


